/// Number of endpoints the shared property-test fixture interns. Local indices generated by
/// the property tests below are drawn from `0..PROPTEST_N`, so every one is in range by
/// construction; slices may still be longer than this (up to 256), repeating local indices,
/// which is realistic and does not affect any property under test.
const PROPTEST_N: u32 = 64;

/// Builds a leaked registry (`Box::leak`, explicitly permitted by this issue for test
/// fixtures) with `n` freshly interned endpoints, plain `ids` and `weights` arrays, and an
/// identity `slice` covering all of them (`0..n`). Each call leaks its own independent
/// arena, per [`EndpointRegistry::install`]'s own contract, so unit tests never share state.
#[allow(
    clippy::expect_used,
    reason = "fixture helper reachable only from #[test] and proptest! bodies; a malformed \
              fixture must fail the calling test loudly rather than propagate a Result \
              through every test signature in this file"
)]
fn fixture(
    n: u32,
) -> (
    &'static EndpointRegistry,
    Vec<EndpointId>,
    Vec<u32>,
    Vec<u32>,
) {
    let (reg, mut writer) = EndpointRegistry::install(n.max(1))
        .expect("n.max(1) is nonzero and far under MAX_CAPACITY");
    let mut ids = Vec::with_capacity(n as usize);
    for i in 0..n {
        let identity = EndpointIdentity {
            addr: EndpointAddr::Socket(SocketAddr::V4(SocketAddrV4::new(
                Ipv4Addr::from(0x0A00_0000u32.wrapping_add(i)),
                80,
            ))),
            hostname: None,
        };
        let id = writer
            .intern(&identity)
            .expect("fixture registry is sized exactly for n distinct endpoints");
        ids.push(id);
    }
    let weights = vec![1u32; n as usize];
    let slice: Vec<u32> = (0..n).collect();
    (reg, ids, weights, slice)
}

/// Declares a once-built fixture of [`PROPTEST_N`] endpoints, so a property test with
/// hundreds of generated cases does not leak hundreds of registries.
///
/// ONE PER PROPERTY TEST, NOT SHARED. `cargo test` runs `#[test]` functions on separate
/// threads by default, and every property test that sets `inflight`/`cost` mutates the
/// registry's stats out of band from the ordinary call graph (`Ordering::Relaxed` stores on
/// shared atomics). A single fixture shared across property tests is consequently racy
/// across THEM, not merely across proptest's own cases within one: one test's write can
/// land between another's `set inflight` and its own read of the same slot, both on
/// different threads. That is not a memory-safety issue (atomics are always well-defined),
/// but it is a real, observed test-flakiness one: an earlier version of this file shared one
/// fixture and `p2c_picks_the_cheaper_of_the_two_sampled` failed intermittently, depending
/// on `cargo test`'s scheduling, with a value that could only have come from a different
/// property test's concurrent write. Each macro invocation below declares its own
/// independent `static`, so no two property tests ever share a mutable endpoint.
macro_rules! once_fixture {
    ($name:ident) => {
        fn $name() -> &'static (&'static EndpointRegistry, Vec<EndpointId>, Vec<u32>) {
            static FIXTURE: OnceLock<(&'static EndpointRegistry, Vec<EndpointId>, Vec<u32>)> =
                OnceLock::new();
            FIXTURE.get_or_init(|| {
                let (reg, ids, weights, _slice) = fixture(PROPTEST_N);
                (reg, ids, weights)
            })
        }
    };
}

once_fixture!(fixture_for_returns_in_range);
once_fixture!(fixture_for_cheaper_of_two);
once_fixture!(fixture_for_exclusion);
once_fixture!(fixture_for_work_bound);

fn default_ctx() -> CostCtx {
    CostCtx {
        now_ms: 1_000,
        decay_ms: 10_000,
        default_rtt_ms: 1_000.0,
        max_requests: u32::MAX,
    }
}

fn set_inflight(stats: &EndpointStats, v: u32) {
    stats.inflight.store(v, Ordering::Relaxed);
}

/// Seeds `stats`'s peak-EWMA estimate to exactly `rtt_ms` as of `now_ms`, by recording one
/// sample into a freshly zeroed word: `record_rtt`'s first call on a zero word packs the
/// clamped sample directly with no blending, so this is exact, not merely close.
fn set_rtt(stats: &EndpointStats, rtt_ms: f32, now_ms: u32) {
    let cfg = EwmaCfg {
        decay_ms: 10_000,
        default_rtt_ms: 1_000.0,
    };
    stats.record_rtt(rtt_ms, now_ms, &cfg);
}

/// `SplitMix64`: three lines, no dependency. Used by every test below that needs many
/// pseudorandom `u64` draws; test 3's own name calls out this exact generator, and reusing
/// one already-exercised implementation across the other draw-heavy tests is simpler than
/// writing several.
fn next_draw(state: &mut u64) -> u64 {
    *state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let mut z = *state;
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

