#[test]
fn sample_two_is_distinct_at_n_two() {
    for draw in [0u64, 1, u64::MAX, 0x1234_5678_9abc_def0] {
        let (a, b) = sample_two(draw, 2);
        assert_ne!(a, b, "draw {draw:#x} produced a duplicate pair");
        assert!(
            (a, b) == (0, 1) || (a, b) == (1, 0),
            "draw {draw:#x} produced an out-of-range pair ({a}, {b})"
        );
    }
}

#[test]
fn sample_two_extremes() {
    assert_eq!(sample_two(0, 8), (0, 1));
    assert_eq!(sample_two(u64::MAX, 8), (7, 6));
}

#[test]
fn sample_two_covers_the_range() {
    let mut rng: u64 = 0x9E37_79B9_7F4A_7C15;
    let mut counts = [0u32; 5];
    for _ in 0..100_000 {
        let draw = next_draw(&mut rng);
        let (a, _b) = sample_two(draw, 5);
        if let Some(c) = counts.get_mut(a as usize) {
            *c += 1;
        }
    }
    for (i, c) in counts.iter().enumerate() {
        assert!(
            *c >= 15_000,
            "index {i} appeared only {c} of 100000 times as `a`; want >= 15000 (25% of the \
             20000 expected under uniformity)"
        );
    }
}

