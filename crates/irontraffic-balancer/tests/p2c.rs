/// Pins the resample budget at EXACTLY three attempts, deterministically, rather than
/// relying on a property test's random luck to reach the branch this matters in. Builds 8
/// endpoints with distinct costs (`inflight` 0..=7, weight 1, so `load_key` is exactly
/// `inflight + 1`), excludes the three CHEAPEST (local indices 0, 1, 2), and brute-force
/// searches, using only this crate's public API, for a `draw` whose first three resample
/// attempts (rotations 0, 21, 42) all fail (each attempt's winner is one of the three
/// excluded, cheapest endpoints, since an excluded entry beats any non-excluded one it is
/// paired against) while a hypothetical FOURTH attempt (rotation 63) would succeed on a
/// non-excluded survivor that is not the true minimum. A `pick_excluding` correctly bounded
/// at three attempts falls through to the deterministic scan for such a draw and returns
/// the true minimum, local index 3; one that tried a fourth attempt would return whatever
/// that attempt happened to sample instead. Confirmed by injection: this test fails (a
/// wrong `Some` instead of `Some(3)`) against the same `0..3u32` to `0..200u32` mutation
/// property test `p2c_work_is_bounded_by_slice_length`'s own doc comment names, closing the
/// gap a random property test can only close probabilistically.
#[test]
fn pick_excluding_never_tries_a_fourth_resample() {
    let (reg, ids, weights, slice) = fixture(8);
    let stats = reg.stats_slice();
    for (i, &id) in ids.iter().enumerate() {
        let st = stats.get(id.0 as usize).expect("stats");
        let inflight = u32::try_from(i).expect("8 endpoints fits in u32");
        set_inflight(st, inflight);
    }
    let cx = default_ctx();
    // fixture(8)'s slice is exactly [0, 1, ..., 7], so slice index, local index, and
    // inflight all coincide here; `exclude` names local indices, which are the same values.
    let exclude = vec![0u32, 1, 2];
    let min_local = 3u32;

    let winner_of = |draw: u64, attempt: u32| -> u32 {
        let d = draw.rotate_left(attempt * 21);
        let (a, b) = sample_two(d, 8);
        let key = |i: u32| -> u32 {
            let local = *slice
                .get(i as usize)
                .expect("i < 8 by sample_two's own I-P1");
            let id = ids.get(local as usize).expect("in range");
            stats
                .get(id.0 as usize)
                .expect("in range")
                .load_key(1.0, &cx)
        };
        if key(b) < key(a) { b } else { a }
    };

    // Candidates come from SplitMix64, not a plain incrementing counter: `draw` and
    // `draw + 1` differ only in their low bits, so an incrementing search leaves the high
    // 32 bits (and therefore sample_two's second index before rotation) nearly constant
    // and starves the search of the diversity the probability estimate below assumes.
    let mut found = None;
    let mut rng = 0x5EED_1234_5678_9ABCu64;
    for _ in 0..2_000_000 {
        let draw = next_draw(&mut rng);
        let first_three_fail = (0..3u32).all(|attempt| exclude.contains(&winner_of(draw, attempt)));
        if !first_three_fail {
            continue;
        }
        let fourth = winner_of(draw, 3);
        if !exclude.contains(&fourth) && fourth != min_local {
            found = Some(draw);
            break;
        }
    }
    let draw = found.expect(
        "a distinguishing draw must exist well within 2000000 candidates: each attempt \
         fails with probability C(5,2)/C(8,2) roughly 64%, and a qualifying fourth attempt \
         is independently likely, so the combined event is common, not rare",
    );

    let result = pick_excluding(
        CostKind::LeastRequest,
        &slice,
        &ids,
        &weights,
        stats,
        &cx,
        draw,
        &exclude,
    );
    assert_eq!(
        result,
        Some(min_local),
        "draw {draw:#x} was constructed so the first three resample attempts fail and a \
         fourth would wrongly succeed on a non-minimal survivor; a correctly bounded \
         pick_excluding must fall through to the deterministic scan and return the true \
         minimum, local index {min_local}, never a fourth attempt's answer"
    );
}

/// Pins the resample budget at EXACTLY three attempts from BELOW, complementing the test
/// above's pin from above. Before this test, the only thing distinguishing "three
/// attempts" from "fewer than three" was `p2c_work_is_bounded_by_slice_length`'s replica,
/// which counts calls probabilistically: confirmed by injection, mutating the real
/// `0..3u32` attempt range to `0..1u32` was caught by that property test in some runs and
/// survived it in others, so the resample count's LOWER bound was pinned only
/// probabilistically.
///
/// Brute-force searches for a draw whose first TWO resample attempts (rotations 0 and 21)
/// both fail (each attempt's winner is one of the three excluded, cheapest endpoints)
/// while the THIRD attempt (rotation 42) succeeds on a non-excluded survivor that is not
/// the true minimum. A `pick_excluding` that tried only one or two attempts (`0..1u32` or
/// `0..2u32` in place of `0..3u32`) would never reach that third attempt's winner and
/// would instead fall through to the deterministic scan and return the true minimum,
/// local index 3, so this test fails deterministically against either mutation, the same
/// way `pick_excluding_never_tries_a_fourth_resample` above pins the upper bound.
#[test]
fn pick_excluding_uses_all_three_resamples() {
    let (reg, ids, weights, slice) = fixture(8);
    let stats = reg.stats_slice();
    for (i, &id) in ids.iter().enumerate() {
        let st = stats.get(id.0 as usize).expect("stats");
        let inflight = u32::try_from(i).expect("8 endpoints fits in u32");
        set_inflight(st, inflight);
    }
    let cx = default_ctx();
    // fixture(8)'s slice is exactly [0, 1, ..., 7], so slice index, local index, and
    // inflight all coincide here; `exclude` names local indices, which are the same
    // values.
    let exclude = vec![0u32, 1, 2];
    let min_local = 3u32;

    let winner_of = |draw: u64, attempt: u32| -> u32 {
        let d = draw.rotate_left(attempt * 21);
        let (a, b) = sample_two(d, 8);
        let key = |i: u32| -> u32 {
            let local = *slice
                .get(i as usize)
                .expect("i < 8 by sample_two's own I-P1");
            let id = ids.get(local as usize).expect("in range");
            stats
                .get(id.0 as usize)
                .expect("in range")
                .load_key(1.0, &cx)
        };
        if key(b) < key(a) { b } else { a }
    };

    let mut found = None;
    let mut rng = 0xB16B_00B5_C0DE_1234u64;
    for _ in 0..2_000_000 {
        let draw = next_draw(&mut rng);
        let first_two_fail = (0..2u32).all(|attempt| exclude.contains(&winner_of(draw, attempt)));
        if !first_two_fail {
            continue;
        }
        let third = winner_of(draw, 2);
        if !exclude.contains(&third) && third != min_local {
            found = Some((draw, third));
            break;
        }
    }
    let (draw, expected_third) = found.expect(
        "a distinguishing draw must exist well within 2000000 candidates, by the same \
         probability argument as pick_excluding_never_tries_a_fourth_resample",
    );

    let result = pick_excluding(
        CostKind::LeastRequest,
        &slice,
        &ids,
        &weights,
        stats,
        &cx,
        draw,
        &exclude,
    );
    assert_eq!(
        result,
        Some(expected_third),
        "draw {draw:#x} was constructed so the first two resample attempts fail and the \
         third succeeds on a non-minimal survivor (local index {expected_third}); a \
         pick_excluding that tried fewer than three attempts would fall through to the \
         deterministic scan instead and wrongly return the true minimum, local index \
         {min_local}"
    );
}

/// Pins the deterministic fallback scan to the GLOBAL MINIMUM among non-excluded entries,
/// not merely the first one the scan happens to visit. Found by mutation testing
/// (`cargo mutants -j 1 --file src/algo/p2c.rs`): replacing the scan's `k < bk` comparator
/// with `k == bk` or `k <= bk` survived every other test in this file, including the
/// fourth-resample test above, because that test's own search only controls which draws
/// make the three bounded resamples fail, not where the scan's start offset lands, and for
/// its particular draw the scan happens to visit the true minimum first anyway.
///
/// Reuses the same 8-distinct-cost, three-cheapest-excluded fixture, and searches for a
/// draw where the scan's start offset (`reduce(low_u32(draw), 8)`, reimplemented here from
/// the issue's own documented Lemire formula and low-bits split, since `reduce` and
/// `low_u32` are `pub(crate)`) lands on one of the non-minimal survivors (4, 5, 6, or 7)
/// rather than on the true minimum (3) or on 0, 1, or 2 (excluded, which the scan would
/// skip on its way to 3 regardless). For such a draw, "return the first non-excluded entry
/// visited" and "return the entry with the lowest key" disagree, so only a scan that
/// genuinely tracks the minimum returns local index 3 here.
#[test]
fn pick_excluding_scan_finds_the_minimum_not_the_first_hit() {
    let (reg, ids, weights, slice) = fixture(8);
    let stats = reg.stats_slice();
    for (i, &id) in ids.iter().enumerate() {
        let st = stats.get(id.0 as usize).expect("stats");
        let inflight = u32::try_from(i).expect("8 endpoints fits in u32");
        set_inflight(st, inflight);
    }
    let cx = default_ctx();
    let exclude = vec![0u32, 1, 2];
    let min_local = 3u32;

    let winner_of = |draw: u64, attempt: u32| -> u32 {
        let d = draw.rotate_left(attempt * 21);
        let (a, b) = sample_two(d, 8);
        let key = |i: u32| -> u32 {
            let local = *slice
                .get(i as usize)
                .expect("i < 8 by sample_two's own I-P1");
            let id = ids.get(local as usize).expect("in range");
            stats
                .get(id.0 as usize)
                .expect("in range")
                .load_key(1.0, &cx)
        };
        if key(b) < key(a) { b } else { a }
    };
    // Reimplements reduce's documented Lemire formula and low_u32's documented bit split,
    // purely to steer the search: both are part of this crate's stable, published algorithm
    // (see the module doc comment on `reduce`), not an implementation detail this test
    // reaches past its own contract to observe.
    let scan_start = |draw: u64| -> u32 {
        #[allow(
            clippy::cast_possible_truncation,
            reason = "reimplements low_u32's documented bit split for a test-only search \
                      key, not production code: intentionally takes the low 32 bits"
        )]
        let x = draw as u32;
        #[allow(
            clippy::cast_possible_truncation,
            reason = "reimplements reduce's documented Lemire formula for a test-only search \
                      key; product < 2^35 (a u32 times 8), so the shifted result is < 8, \
                      always fits in u32"
        )]
        let start = ((u64::from(x) * 8) >> 32) as u32;
        start
    };

    let mut found = None;
    let mut rng = 0xFACE_FEED_C0FF_EE00u64;
    for _ in 0..2_000_000 {
        let draw = next_draw(&mut rng);
        let all_three_fail = (0..3u32).all(|attempt| exclude.contains(&winner_of(draw, attempt)));
        if !all_three_fail {
            continue;
        }
        if scan_start(draw) >= 4 {
            found = Some(draw);
            break;
        }
    }
    let draw = found.expect(
        "a draw whose scan start lands past the minimum must exist well within 2000000 \
         candidates: P(all three resamples fail) is roughly 26% and P(scan start >= 4) is \
         50%, independent of it, so the combined event is common, not rare",
    );

    let result = pick_excluding(
        CostKind::LeastRequest,
        &slice,
        &ids,
        &weights,
        stats,
        &cx,
        draw,
        &exclude,
    );
    assert_eq!(
        result,
        Some(min_local),
        "draw {draw:#x}: the scan's start offset does not land on the minimum, so a scan \
         that stopped at the first non-excluded entry instead of tracking the lowest key \
         would return something other than local index {min_local} here"
    );
}

#[test]
fn pick_excluding_rejects_an_oversized_exclude_list() {
    let (reg, ids, weights, slice) = fixture(64);
    let stats = reg.stats_slice();
    let cx = default_ctx();
    let exclude: Vec<u32> = (0..64u32).collect();

    if cfg!(debug_assertions) {
        // A debug build's debug_assert fires before any key evaluation, which is a
        // stronger statement than "returns None": it never reaches the point where it
        // COULD have entered an O(u * r) loop. Caught with catch_unwind rather than
        // `#[should_panic]` so this stays one test whose two branches share the same
        // fixture and exclude list, instead of two nearly-identical tests.
        let outcome = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            pick_excluding(
                CostKind::LeastRequest,
                &slice,
                &ids,
                &weights,
                stats,
                &cx,
                0,
                &exclude,
            )
        }));
        assert!(
            outcome.is_err(),
            "a debug build must debug_assert when exclude.len() > MAX_EXCLUDE"
        );
    } else {
        let result = pick_excluding(
            CostKind::LeastRequest,
            &slice,
            &ids,
            &weights,
            stats,
            &cx,
            0,
            &exclude,
        );
        assert_eq!(
            result, None,
            "a release build must return None for an oversized exclude list, not a value"
        );

        // "the point is that the function returns before entering any O(u * r) loop":
        // in release the debug_assert compiles out, so wall time as u grows from 64 to
        // 4096 is what is left to show the rejection did not scale with u.
        let (reg_big, ids_big, weights_big, slice_big) = fixture(4096);
        let stats_big = reg_big.stats_slice();
        let exclude_big: Vec<u32> = (0..4096u32).collect();

        let iterations = 20_000u32;
        let small_elapsed = {
            let start = std::time::Instant::now();
            for i in 0..iterations {
                let _ = pick_excluding(
                    CostKind::LeastRequest,
                    &slice,
                    &ids,
                    &weights,
                    stats,
                    &cx,
                    u64::from(i),
                    &exclude,
                );
            }
            start.elapsed()
        };
        let big_elapsed = {
            let start = std::time::Instant::now();
            for i in 0..iterations {
                let _ = pick_excluding(
                    CostKind::LeastRequest,
                    &slice_big,
                    &ids_big,
                    &weights_big,
                    stats_big,
                    &cx,
                    u64::from(i),
                    &exclude_big,
                );
            }
            start.elapsed()
        };
        assert!(
            big_elapsed <= small_elapsed.saturating_mul(20)
                || big_elapsed < std::time::Duration::from_millis(5),
            "u = 4096 took {big_elapsed:?} against u = 64's {small_elapsed:?}; an O(1) \
             rejection must not scale with u"
        );
    }
}

/// `CostKind::PeakEwma` reaching `pick_excluding`'s empty-exclude dispatch (line ~403).
